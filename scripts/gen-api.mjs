// Refreshes the frontend's generated API files from the backend's OpenAPI schema:
//   src/types/openapi.gen.ts      the API's TypeScript types (openapi-typescript)
//   src/types/api-routes.gen.json every "METHOD /path" the backend serves ({} for a path parameter)
//   src/types/units.gen.ts        the unit of every ratio-like field (from the backend's x-unit markers)
//   src/types/api-fields.gen.json every response schema and the properties of every schema, for the field-coverage test
// Usage: npm run gen:api                       (backend running on http://localhost:8000)
//        API_URL=http://localhost:8010 npm run gen:api
//        npm run gen:api -- --file openapi.json    (a schema saved to a file; no server needed)
//        npm run gen:api -- --check                (write nothing; exit 1 when a committed file is out of date)
// The backend's `python scripts/generate_api_reference.py --frontend` calls this with a file, so one command refreshes both repos.
// The API's documentation is the backend's generated reference (backend/docs/api-reference.md), built from the same
// schema; nothing is copied here.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const args = process.argv.slice(2)
const check = args.includes('--check')
const fileFlag = args.indexOf('--file')
const file = fileFlag >= 0 ? args[fileFlag + 1] : process.env.OPENAPI_FILE
const base = (process.env.API_URL ?? 'http://localhost:8000').replace(/\/$/, '')
const url = `${base}/openapi.json`
const FILES = ['openapi.gen.ts', 'api-routes.gen.json', 'units.gen.ts', 'api-fields.gen.json']

// A line-ending difference is not a difference: a Windows checkout may turn the committed files into CRLF.
const lf = (text) => text.replace(/\r\n/g, '\n')

try {
  const spec = file ? JSON.parse(readFileSync(file, 'utf8')) : await (await fetch(url)).json()
  const out = check ? mkdtempSync(join(tmpdir(), 'gen-api-')) : 'src/types'

  // openapi-typescript reads a file path or a URL, so a schema is given by whichever it came from.
  execFileSync(process.execPath, ['node_modules/openapi-typescript/bin/cli.js', file ?? url, '-o', join(out, 'openapi.gen.ts')], {
    stdio: 'inherit',
  })

  const routes = Object.entries(spec.paths)
    .flatMap(([path, item]) =>
      ['get', 'post', 'put', 'patch', 'delete']
        .filter((method) => method in item)
        .map((method) => `${method.toUpperCase()} ${path.replace(/\{[^}]+\}/g, '{}')}`),
    )
    .sort()
  writeFileSync(join(out, 'api-routes.gen.json'), JSON.stringify(routes, null, 2) + '\n')

  // The unit of every ratio-like field, from the backend's `x-unit` markers (backend/src/data/reference/units.py), so no table of
  // units is kept by hand. Only the three kinds the app converts are listed (`whole_percent` is called 'percent' here).
  const kinds = { fraction: 'fraction', whole_percent: 'percent', points: 'points' }
  const units = Object.entries(spec.components.schemas)
    .flatMap(([schema, body]) =>
      Object.entries(body.properties ?? {})
        .filter(([, property]) => kinds[property['x-unit']])
        .map(([field, property]) => [`${schema}.${field}`, kinds[property['x-unit']]]),
    )
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  writeFileSync(
    join(out, 'units.gen.ts'),
    [
      "// Generated by scripts/gen-api.mjs from the backend's `x-unit` markers. Do not edit.",
      'export const UNIT_BY_FIELD = {',
      ...units.map(([field, unit]) => `  '${field}': '${unit}',`),
      '} as const',
      '',
    ].join('\n'),
  )

  // Which schemas a successful response can carry (followed through $ref, items, anyOf and so on), and the properties of
  // every schema. The field-coverage test and `npm run coverage:api` read this: a screen must decide every property of
  // the schemas it reads, and every response schema must be claimed by some screen.
  const schemas = spec.components.schemas
  const responses = new Set()
  const follow = (node) => {
    if (!node || typeof node !== 'object') return
    if (typeof node.$ref === 'string') {
      const name = node.$ref.split('/').pop()
      if (!responses.has(name)) {
        responses.add(name)
        follow(schemas[name])
      }
      return
    }
    Object.values(node).forEach(follow)
  }
  for (const item of Object.values(spec.paths)) {
    for (const operation of Object.values(item)) {
      for (const [status, response] of Object.entries(operation?.responses ?? {})) {
        if (status.startsWith('2')) follow(response.content?.['application/json']?.schema)
      }
    }
  }
  const fields = Object.fromEntries(
    Object.keys(schemas)
      .sort()
      .map((name) => [name, Object.keys(schemas[name].properties ?? {}).sort()]),
  )
  writeFileSync(join(out, 'api-fields.gen.json'), JSON.stringify({ responses: [...responses].sort(), fields }, null, 2) + '\n')

  if (check) {
    const stale = FILES.filter((name) => {
      const committed = join('src/types', name)
      return !existsSync(committed) || lf(readFileSync(committed, 'utf8')) !== lf(readFileSync(join(out, name), 'utf8'))
    })
    if (stale.length) {
      console.error(`gen:api --check: out of date: ${stale.join(', ')}. Run \`npm run gen:api\` and commit the files.`)
      process.exitCode = 1
    }
  }
} catch (error) {
  console.error(`gen:api failed: ${error.message}`)
  process.exitCode = 1
}
